QUESTIONS_PATH = Path("eval/questions.jsonl")
HISTORY_PATH = Path("eval/history.csv")

MODEL_TO_DOC = {
    "SB 2000HF": "sma_sunnyboy_hf_2-3kw",
    "SB 2500HF": "sma_sunnyboy_hf_2-3kw",
    "SB 3000HF": "sma_sunnyboy_hf_2-3kw",
    "SB 3000TL": "sma_sunnyboy_tl_3-5kw",
    "SB 4000TL": "sma_sunnyboy_tl_3-5kw",
    "SB 5000TL": "sma_sunnyboy_tl_3-5kw",
    "Fronius Symo 10.0-3-M": "fronius_symo_10-20kw",
    "Fronius Symo 12.5-3-M": "fronius_symo_10-20kw",
    "Fronius Symo 15.0-3-M": "fronius_symo_10-20kw",
    "Fronius Symo 17.5-3-M": "fronius_symo_10-20kw",
    "Fronius Symo 20.0-3-M": "fronius_symo_10-20kw",
}

JUDGE_PROMPT = """You are evaluating an answer generated by a RAG system.

Passages retrieved:
{passages}

Question: {question}
Gold answer: {gold_answer}
Generated answer: {generated}

Answer the following with YES or NO only, no explanation:
1. Is the generated answer FAITHFUL to the passages? (uses only information present in the passages)
2. Is the generated answer CORRECT compared to the gold answer? (captures the same key facts)

Respond exactly like this:
FAITHFUL: YES
CORRECT: YES"""


def load_questions() -> list[dict]:
    with open("eval/questions.jsonl") as f:
        questions = [json.loads(line) for line in f if line.strip()]

    return questions


def run_pipeline(qdrant, llm, question: dict) -> dict:
    passages = retrieve(qdrant, question["question"])
    rerank_scores = [p.get("_score", 0.0) for p in passages]

    if should_abstain(rerank_scores):
        return {
            "passages": passages,
            "answer": None,
            "abstained": True,
            "rerank_scores": rerank_scores,
        }

    model = MODEL_TO_DOC.get(question.get("model"))
    abstain_reason = wrong_model_abstain(passages, model)
    if abstain_reason:
        return {
            "passages": passages,
            "answer": None,
            "abstained": True,
            "rerank_scores": rerank_scores,
        }

    answer = generate_answer(llm, question["question"], passages)
    answer = check_citations(answer, passages)

    return {
        "passages": passages,
        "answer": answer,
        "abstained": False,
        "rerank_scores": rerank_scores,
    }


def citation_accuracy(answer: dict, question: dict) -> float | None:
    if question["gold_doc"] is None:
        return None

    for c in answer["citations"]:
        if question["gold_doc"] in c and f"p.{question['gold_page']}" in c:
            return 1.0

    return 0.0


def judge_answer(llm, passages: list[dict], question: dict, answer: dict) -> tuple[bool, bool]:
    passages_text = "\n".join(f"[{p['doc_id']} p.{p['page']}] {p['text']}" for p in passages)

    prompt = JUDGE_PROMPT.format(
        passages=passages_text,
        question=question["question"],
        gold_answer=question["gold_answer"],
        generated=json.dumps(answer),
    )

    response = llm.generate(prompt)

    faithful = "FAITHFUL: YES" in response.upper()
    correct = "CORRECT: YES" in response.upper()

    return faithful, correct


def compute_abstain_metrics(results: list[dict], questions: list[dict]) -> tuple[float, float]:
    should = {q["id"] for q in questions if q["type"] in ("wrong_model_trap", "unanswerable")}
    did = {r["id"] for r in results if r["abstained"]}

    correct_abstains = did & should

    precision = len(correct_abstains) / len(did) if did else 0.0
    recall = len(correct_abstains) / len(should) if should else 0.0

    return precision, recall


def main():
    qdrant = QdrantClient(host="localhost", port=6333)
    llm = OllamaClient()

    questions = load_questions()
    results = []

    for i, q in enumerate(questions, 1):
        print(f"[{i}/{len(questions)}] {q['id']} {q['type']}")

        pipeline_out = run_pipeline(qdrant, llm, q)

        result = {
            "id": q["id"],
            "type": q["type"],
            "abstained": pipeline_out["abstained"],
        }

        if not pipeline_out["abstained"] and pipeline_out["answer"]:
            answer = pipeline_out["answer"]
            result["citation_accuracy"] = citation_accuracy(answer, q)

            if q["gold_doc"] is not None:
                faithful, correct = judge_answer(llm, pipeline_out["passages"], q, answer)
                result["faithful"] = faithful
                result["correct"] = correct

        results.append(result)

    cit_scores = [r["citation_accuracy"] for r in results if r.get("citation_accuracy") is not None]
    faithful_scores = [r["faithful"] for r in results if "faithful" in r]
    correct_scores = [r["correct"] for r in results if "correct" in r]
    abstain_p, abstain_r = compute_abstain_metrics(results, questions)

    print(f"\ncitation_accuracy : {sum(cit_scores) / len(cit_scores):.3f}")
    print(f"faithfulness      : {sum(faithful_scores) / len(faithful_scores):.3f}")
    print(f"correctness       : {sum(correct_scores) / len(correct_scores):.3f}")
    print(f"abstain_precision : {abstain_p:.3f}")
    print(f"abstain_recall    : {abstain_r:.3f}")

    commit = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"]).decode().strip()
    row = {
        "date": date.today().isoformat(),
        "commit": commit,
        "citation_accuracy": round(sum(cit_scores) / len(cit_scores), 3),
        "faithfulness": round(sum(faithful_scores) / len(faithful_scores), 3),
        "correctness": round(sum(correct_scores) / len(correct_scores), 3),
        "abstain_precision": round(abstain_p, 3),
        "abstain_recall": round(abstain_r, 3),
    }
    answer_history = Path("eval/answer_history.csv")
    write_header = not answer_history.exists()
    with open(answer_history, "a", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=row.keys())
        if write_header:
            writer.writeheader()
        writer.writerow(row)


if __name__ == "__main__":
    main()
